def as_built(pickups, records):
    """Champion vs the builder's return stage; held rows reported as coverage."""
    common_rows, held = [], []
    for r in records:
        if not (r["scored"] and r["year"] in replay.EVAL_YEARS):
            continue
        if not (r["stage"] in (bpt.STAGE_ESTABLISHED, bpt.STAGE_NEW) and not r["restart"]
                and not r["season_spec"] and r["days_since"] <= bpt.STALE_DAYS and not r["will_call"]):
            continue
        h = pickups[r["cid"]][:r["k"]]
        from exp_return_guards import v1_rate
        ret = v1_rate(h, r["date"])
        if not ret:
            continue
        row = {"cid": r["cid"], "name": r["name"], "year": r["year"], "actual": r["actual"],
               "base": r["pred"], "since": ret[2]}
        if ret[0] is None:
            held.append(row)
        else:
            common_rows.append(dict(row, cand=ret[0] * r["exposure"]))
    return common_rows, held


def band(rows, years):
    ratios = sorted(r["actual"] / r["cand"] for r in rows if r["year"] in years and r["cand"] > 0)
    q = statistics.quantiles(ratios, n=10)
    return q[1], q[7], len(ratios)


def as_built_md(pickups, records):
    rows, held = as_built(pickups, records)
    out, yrs = harness.evaluate("U", "Return stage as built", "returns ranked under both", rows)
    md = ["## As first built, 2026-10-17 (V1: `bpt.rate_same_time_last_year`, no reopening gate; the builder is V4 since 10-18, `return_guards.md`)", "",
          harness.table(out), "", harness.year_table({"Return stage as built": yrs}), ""]
    hs = m.summary([dict(r) for r in held], "base") if held else None
    md.append(f"Held as insufficient data (no past year at that date): {len(held)} pickups"
              + (f" ({hs['customers']} customers, {hs['actual_gal']:,.0f} gal); the champion's projection "
                 f"of them scored {hs['wape']:.1f}% WAPE, {hs['bias']:+.1f}% bias." if hs else "."))
    lo, hi, n = band(rows, replay.DEV_YEARS)
    lo_a, hi_a, n_a = band(rows, replay.EVAL_YEARS)
    md.append(f"\nRange factors (20th / 80th percentile of actual ÷ projected): dev 2021–23 "
              f"x{lo:.2f} to x{hi:.2f} ({n} pickups); all eval years x{lo_a:.2f} to x{hi_a:.2f} ({n_a}).")
    return "\n".join(md)


if __name__ == "__main__":
    main()
