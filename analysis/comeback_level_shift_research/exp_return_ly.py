#!/usr/bin/env python3
"""
Sarge's return rule (2026-10-17) for 181-365 d returns, research only.

Today R2 and R3 after such a gap are projected by the 50/50, whose windows
include the gap (diluted). Proposed:

    R2 (since 1)  rate = same time last year(s): production per day in the
                  surrounding month (as-of +/- 15 d), 1-3 years back,
                  averaged over the years with data (bpt.window_rate on the
                  spread daily production -- the seasonal stage's "LY")
    R3 (since 2)  rate = 1/2 x (R2 gallons / days R1 -> R2)
                       + 1/2 x the same-time-last-year(s) rate
    R4 on         unchanged: the dormant restart

Variants, declared before the first run:
    U1  as above, the month centred on the as-of date, years back
    U2  last years' production over the SAME days being projected
        (clock -> as-of, shifted back), so the rate matches the interval
Scope: established/new-stage pickups (closers keep their open-season rate;
none here are seasonal-stage). Where no year has data the candidate has no
rate: it is scored on identical pickups with the champion as fallback, and
the count is reported (a hold instead would be coverage, not accuracy).
A1 (open days, loose calendar) is reported on the same pickups.

    RESEARCH_CACHE=... python3 exp_return_ly.py
"""

import statistics
from collections import Counter
from datetime import timedelta

import champion as ch
import common as c
import exp_comeback as ec
import harness
import metrics as m
import replay
from replay import bpt

HERE = c.HERE
HALF_WIDTH = 15
YEARS_BACK = (1, 2, 3)
SCOPE = (181, 365)


def ly_month(daily, first, asof):
    rates = [bpt.window_rate(daily, first, asof - timedelta(days=bpt.YEAR_DAYS * b), HALF_WIDTH)
             for b in YEARS_BACK]
    rates = [r for r in rates if r is not None]
    return statistics.fmean(rates) if rates else None, len(rates)


def ly_span(daily, first, start, end):
    rates = []
    for b in YEARS_BACK:
        s, e = start - timedelta(days=bpt.YEAR_DAYS * b), end - timedelta(days=bpt.YEAR_DAYS * b)
        if s <= first + timedelta(days=60) or e <= s:
            continue
        days = (e - s).days
        rates.append(sum(daily.get(s + timedelta(days=i + 1), 0.0) for i in range(days)) / days)
    return statistics.fmean(rates) if rates else None, len(rates)


def build(pickups, ev, cals):
    rows = []
    for r in ev:
        if not (r["scored"] and r["since"] in (1, 2) and SCOPE[0] <= r["ev_gap"] <= SCOPE[1]
                and r["stage"] in (bpt.STAGE_ESTABLISHED, bpt.STAGE_NEW) and not r["restart"]):
            continue
        ps = pickups[r["cid"]]
        h = ps[:r["k"]]
        i = r["ev_i"]
        daily = c.ss.daily_production(h)
        first = h[0]["date"]
        days = r["exposure"]
        u1, n1 = ly_month(daily, first, r["date"])
        u2, n2 = ly_span(daily, first, r["clock_start"], r["date"])
        cand = {}
        post = bpt.bsm.rate_span(h, i, i + 1) if r["since"] == 2 else None
        for name, ly in (("U1 month around the date", u1), ("U2 same days last year", u2)):
            if ly is None:
                continue
            rate = ly if r["since"] == 1 else (0.5 * post + 0.5 * ly if post is not None else None)
            if rate is not None:
                cand[name] = rate * days
        closed = cals.get(r["cid"], ps, r["year"], "loose")
        a1 = ec.a_rate(r, h, closed) if closed else None
        if a1 is not None:
            cand["A1 open days (loose)"] = a1 * c.open_days(r["clock_start"], r["date"], closed)
        _, pre_gaps, year_gal = ec.pre_gap(ps, i)
        rows.append({"cid": r["cid"], "name": r["name"], "year": r["year"], "actual": r["actual"],
                     "base": r["pred"], "since": r["since"], "cand": cand, "ly_years": n1,
                     "season_type": ec.season_type(ps, i), "return_class": ec.return_class(ps, i),
                     "pre_year_gal": year_gal})
    return rows


def main():
    pickups, _, _, records = ch.load_or_build()
    cals = c.Calendars()
    ev = ec.attach_events(pickups, records)
    rows = [r for r in build(pickups, ev, cals) if r["year"] in replay.EVAL_YEARS]
    results, yearly = [], {}
    names = ("U1 month around the date", "U2 same days last year", "A1 open days (loose)")
    md = ["# Sarge's return rule: same time last year(s) for R2, half recent for R3", "",
          "Generated by `exp_return_ly.py`. 181–365 d returns, established/new stage, R2 and R3 "
          f"({len(rows)} pickups, {len({r['cid'] for r in rows})} customers, eval years). "
          "Candidates were declared in the script header before the first run.", "",
          "## Coverage", "",
          f"- At least one past year with data: U1 {sum('U1 month around the date' in r['cand'] for r in rows)} "
          f"of {len(rows)} pickups; U2 {sum('U2 same days last year' in r['cand'] for r in rows)}; "
          f"A1 {sum('A1 open days (loose)' in r['cand'] for r in rows)}.",
          "- Past years with data behind U1 (pickups): " + ", ".join(
              f"{k}: {v}" for k, v in sorted(Counter(r["ly_years"] for r in rows).items())) + ".", ""]
    for name in names:
        fired = ec.head_to_head(rows, name, fallback=False)
        yearly[name] = c.evaluate(results, "U", name, "181-365 d return, R2-R3, where the candidate exists", fired)
        yearly[name + ", champion fallback"] = c.evaluate(
            results, "U", name + ", champion fallback", "181-365 d return, R2-R3, all", ec.head_to_head(rows, name))
    md += ["## Results", "", harness.table(results), "",
           "## Per year (Δ WAPE points)", "", harness.year_table(yearly), ""]
    for name in names[:2]:
        sub = ec.head_to_head(rows, name, fallback=False)
        md.append(f"## {name}: by subset\n")
        md.append(ec.split_md(sub, lambda r: f"R{r['since'] + 1}", "Pickup"))
        md.append("")
        md.append(ec.split_md(sub, lambda r: r["season_type"], "Season type"))
        md.append("")
        md.append(ec.split_md(sub, lambda r: r["return_class"], "Return class"))
        md.append("")
        md.append(ec.split_md(sub, lambda r: f"{r['ly_years']} past year(s)", "Years of data"))
        md.append("\n" + c.top_contributors(sub) + "\n")
    # Head to head U1 vs A1 where both exist
    both = [r for r in rows if "U1 month around the date" in r["cand"] and "A1 open days (loose)" in r["cand"]]
    if both:
        hh = [dict({k: v for k, v in r.items() if k != "cand"},
                   base=r["cand"]["A1 open days (loose)"], cand=r["cand"]["U1 month around the date"]) for r in both]
        cmp = m.compare(hh)
        md.append(f"## U1 vs A1 where both exist\n\n{cmp['pickups']} pickups ({cmp['customers']} customers): "
                  f"A1 {cmp['base_wape']:.1f}% → U1 {cmp['cand_wape']:.1f}%, Δ {cmp['d_wape']:+.2f} "
                  f"({m.ci(cmp)}); bias {cmp['base_bias']:+.1f}% → {cmp['cand_bias']:+.1f}%.\n")
    if hasattr(bpt, "rate_same_time_last_year"):
        md.append(as_built_md(pickups, records))
    (HERE / "return_last_year.md").write_text("\n".join(md) + "\n")
    harness.write_results(HERE / "results_U.csv", results)
    print("wrote return_last_year.md, results_U.csv;", len(rows), "pickups")



